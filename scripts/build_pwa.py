#!/usr/bin/env python3
"""Generate and validate GitHub Pages PWA assets for Android/PWABuilder.

Builds Web PWA assets only. Never edits iOS icons, native apps or signing keys.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

BASE = '/jomon-pix/'
SOURCE_ICON = Path('ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png')
BASE_PRECACHE = ('assets', 'stickers', 'frame-previews', 'backgrounds', 'mediapipe', 'third-party')
REQUIRED_PUBLIC = ('mediapipe/face_landmarker.task', 'mediapipe/pose_landmarker_lite.task',
                   'mediapipe/vision_wasm_internal.wasm',
                   'mediapipe/vision_wasm_module_internal.wasm')

def build(out: Path) -> None:
    if not (out / 'index.html').is_file():
        raise FileNotFoundError('Run npm run build before generating the PWA')
    manifest = json.loads((out / 'manifest.webmanifest').read_text(encoding='utf-8'))
    if (manifest.get('start_url'), manifest.get('scope'), manifest.get('id')) != (BASE, BASE, BASE):
        raise ValueError('Incorrect PWA base URL / scope / identity')
    if manifest.get('display') != 'standalone' or manifest.get('name') != 'JOMON PIX':
        raise ValueError('Incorrect Android PWA manifest')
    if not SOURCE_ICON.is_file():
        raise FileNotFoundError(f'Approved JOMON PIX icon missing: {SOURCE_ICON}')
    icons = out / 'pwa-icons'
    icons.mkdir(exist_ok=True)
    with Image.open(SOURCE_ICON) as original:
        if original.size != (1024, 1024):
            raise ValueError('Original approved icon must be 1024x1024')
        img = original.convert('RGB')
        for size in (192, 512):
            img.resize((size, size), Image.Resampling.LANCZOS).save(
                icons / f'icon-{size}.png', optimize=True
            )
        # Separate, deliberately padded icon for Android adaptive icon masks.
        # The approved icon is kept unchanged for the regular 'any' icon.
        maskable = Image.new('RGB', (512, 512), '#fff6fb')
        inset = 280
        maskable.paste(
            img.resize((inset, inset), Image.Resampling.LANCZOS),
            ((512 - inset) // 2, (512 - inset) // 2)
        )
        maskable.save(icons / 'icon-maskable-512.png', optimize=True)

    for icon in manifest['icons']:
        target = out / icon['src']
        if not target.is_file() or target.suffix.lower() != '.png':
            raise ValueError(f'Invalid manifest icon: {icon}')
        width, height = map(int, icon['sizes'].split('x'))
        with Image.open(target) as check:
            if check.size != (width, height):
                raise ValueError(f'Incorrect icon dimensions: {target}')

    # Install the HTML, hashed Vite JS/CSS and the small built-in visual
    # library together. Otherwise an offline PWA may show only broken images.
    critical = [BASE, BASE + 'manifest.webmanifest']
    for folder in BASE_PRECACHE:
        root = out / folder
        if not root.is_dir():
            raise FileNotFoundError(f'Expected built asset folder: {root}')
        for path in sorted(root.rglob('*')):
            if path.is_file():
                critical.append(BASE + path.relative_to(out).as_posix())
    critical.extend(BASE + path.relative_to(out).as_posix() for path in sorted(icons.glob('*.png')))
    critical = list(dict.fromkeys(critical))

    for name in REQUIRED_PUBLIC:
        if not (out / name).is_file():
            raise FileNotFoundError(f'Offline AI asset missing: {name}')
    if not any(item.endswith('.js') for item in critical):
        raise ValueError('No Vite JavaScript included in the offline shell')
    if not any(item.startswith(BASE + 'stickers/') for item in critical):
        raise ValueError('No photo stickers included in the offline shell')

    # Verify the exact generated resource sizes and content hashes: two
    # releases with equal-size files must NOT share an obsolete cache version.
    inventory = []
    for item in critical:
        local = out / ('index.html' if item == BASE else item.removeprefix(BASE))
        h = hashlib.sha256(local.read_bytes()).hexdigest()
        inventory.append((item, local.stat().st_size, h))
    version = hashlib.sha256(json.dumps(inventory).encode()).hexdigest()[:16]
    sw = r"""/* Generated by scripts/build_pwa.py. Web/PWABuilder only. */
'use strict';
const ROOT = '/jomon-pix/';
const VERSION = '__VERSION__';
const SHELL = 'jomon-pix-shell-' + VERSION;
const RUNTIME = 'jomon-pix-runtime-' + VERSION;
const PRECACHE = __PRECACHE__;
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL);
    await cache.addAll(PRECACHE);
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) =>
      (name.startsWith('jomon-pix-shell-') && name !== SHELL) ||
      (name.startsWith('jomon-pix-runtime-') && name !== RUNTIME)
    ).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(ROOT)) return;
  if (url.pathname.endsWith('/sw.js')) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(SHELL);
      try {
        const response = await fetch(request);
        if (response.ok) await cache.put(ROOT, response.clone());
        return response;
      } catch {
        return (await cache.match(ROOT)) || Response.error();
      }
    })());
    return;
  }

  // Local editing assets are cached, never image uploads or user photos.
  event.respondWith((async () => {
    const shell = await caches.open(SHELL);
    const precached = await shell.match(request, { ignoreSearch: true });
    if (precached) return precached;
    const runtime = await caches.open(RUNTIME);
    const cached = await runtime.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') {
      await runtime.put(request, response.clone());
    }
    return response;
  })());
});
"""
    sw = sw.replace('__VERSION__', version).replace('__PRECACHE__', json.dumps(critical, ensure_ascii=False))
    (out / 'sw.js').write_text(sw, encoding='utf-8')
    if any(not p.startswith(BASE) for p in critical):
        raise ValueError('PWA contains assets outside application scope')
    print(f'PWABuilder PWA: {len(critical)} local app-shell/assets precached, '
          f'192/512 and maskable icons verified; sha={version}', flush=True)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=Path('dist'))
    args = parser.parse_args()
    build(args.out)
