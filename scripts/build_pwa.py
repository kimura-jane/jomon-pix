#!/usr/bin/env python3
"""Create JOMON PIX GitHub Pages PWA release assets after 'vite build'.

Does not touch or modify the iOS app, Play Console or signing keys.
Uses the already-approved native app icon as the single visual source.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

BASE = '/jomon-pix/'
SOURCE_ICON = Path('ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png')

def build(out: Path) -> None:
    assert (out / 'index.html').is_file(), 'Run npm run build first'
    manifest_path = out / 'manifest.webmanifest'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    assert manifest['start_url'] == BASE and manifest['scope'] == BASE
    assert manifest['id'] == BASE
    assert manifest['name'] == 'JOMON PIX'
    assert SOURCE_ICON.is_file(), f'Missing approved app icon: {SOURCE_ICON}'
    icons_dir = out / 'pwa-icons'
    icons_dir.mkdir(exist_ok=True)
    with Image.open(SOURCE_ICON) as original:
        assert original.size == (1024, 1024), 'Approved icon must be 1024px'
        for size in (192, 512):
            destination = icons_dir / f'icon-{size}.png'
            original.convert('RGB').resize((size, size), Image.Resampling.LANCZOS).save(
                destination, 'PNG', optimize=True
            )
            with Image.open(destination) as check:
                assert check.size == (size, size)

    # Cache the actual complete Vite JS/CSS shell. The entrypoint and lazy
    # module filenames are content-hashed. This avoids broken offline launches
    # caused by caching only HTML while omitting imported JavaScript bundles.
    precache = [BASE, BASE + 'manifest.webmanifest']
    precache += [BASE + f'pwa-icons/icon-{s}.png' for s in (192, 512)]
    precache += [
        BASE + path.relative_to(out).as_posix()
        for path in sorted((out / 'assets').rglob('*'))
        if path.is_file() and path.suffix in ('.js', '.css', '.mjs')
    ]
    precache = list(dict.fromkeys(precache))
    if len(precache) < 5:
        raise RuntimeError('Missing Vite JS/CSS files; refusing to publish incomplete PWA')
    signature = hashlib.sha256(json.dumps(
        {p: (out / p.removeprefix(BASE)).stat().st_size if p != BASE else
         (out / 'index.html').stat().st_size for p in precache},
        sort_keys=True
    ).encode()).hexdigest()[:16]
    # Preserve the first cache, fall back on cache if offline, and only cache
    # same-origin GETs under the PWA scope. Never intercept file uploads,
    # POST requests or other origins. Camera/photos are processed in the app
    # and are not added to the Service Worker cache.
    script = r"""/* Generated by scripts/build_pwa.py. Do not edit manually. */
'use strict';
const ROOT = '/jomon-pix/';
const VERSION = '__VERSION__';
const SHELL_CACHE = 'jomon-pix-shell-' + VERSION;
const RUNTIME_CACHE = 'jomon-pix-runtime-v1';
const PRECACHE = __PRECACHE__;
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await cache.addAll(PRECACHE);
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) =>
      key.startsWith('jomon-pix-shell-') && key !== SHELL_CACHE
    ).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(ROOT)) return;
  if (url.pathname.endsWith('/sw.js')) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(SHELL_CACHE);
      try {
        const response = await fetch(request);
        if (response.ok) await cache.put(ROOT, response.clone());
        return response;
      } catch {
        return (await cache.match(ROOT)) || Response.error();
      }
    })());
    return;
  }

  // Versioned JS/CSS and package assets: prefer cached bytes offline.
  event.respondWith((async () => {
    const shell = await caches.open(SHELL_CACHE);
    const cachedShell = await shell.match(request);
    if (cachedShell) return cachedShell;
    const runtime = await caches.open(RUNTIME_CACHE);
    const cached = await runtime.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') {
      await runtime.put(request, response.clone());
    }
    return response;
  })());
});
"""
    script = script.replace('__VERSION__', signature).replace(
        '__PRECACHE__', json.dumps(precache, ensure_ascii=False)
    )
    (out / 'sw.js').write_text(script, encoding='utf-8')
    assert not any(x.startswith('http') for x in precache)
    print(f'PWABuilder: verified PNG icons, manifest and {len(precache)} precached URLs')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=Path('dist'))
    args = parser.parse_args()
    build(args.out)
